function destructible(maximumHitPoints, overrides = {}) {
  return Object.freeze({
    kind: "destructible",
    maximumHitPoints,
    basicAttackDamage: 100,
    penetration: 0,
    physicalArmor: 0,
    energyShield: 0,
    attackRange: 0,
    attackIntervalMs: 1000,
    canAttack: false,
    isStructure: false,
    hitsToDestroy: 3,
    ...overrides,
  });
}

